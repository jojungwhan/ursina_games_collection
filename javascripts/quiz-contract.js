        selector: function(className) {
            return '.' + className;
        },

        /**
         * Build a data attribute selector
         */
        dataSelector: function(attrName, value) {
            if (value !== undefined) {
                return '[data-' + this._camelToKebab(attrName) + '="' + value + '"]';
            }
            return '[data-' + this._camelToKebab(attrName) + ']';
        },

        /**
         * Convert camelCase to kebab-case for data attributes
         */
        _camelToKebab: function(str) {
            return str.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
        },

        /**
         * Validate element exists and log warning if not
         * @param {HTMLElement|null} element - Element to validate
         * @param {string} context - Description for warning message
         * @returns {boolean} True if element exists
         */
        validateElement: function(element, context) {
            if (!element) {
                console.warn('[QuizContract] Element not found:', context);
                return false;
            }
            return true;
        }
